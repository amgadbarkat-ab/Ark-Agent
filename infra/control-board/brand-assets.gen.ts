/**
 * Writes brand-assets.ts: the company's favicons and the Geist fonts from `brand/`, as base64, so the
 * Worker can serve them itself (a Worker has no files to read at run time, and the CSP allows nothing
 * from another origin). Run it again after `brand/` changes:  bun infra/control-board/brand-assets.gen.ts
 * brand.test.ts fails while the embedded copy differs from the brand folder.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const brand = join(import.meta.dir, "..", "..", "brand");

/** Published path, file under brand/, content type. Only what the board's pages load. */
export const ASSET_FILES = [
  ["/favicon.ico", "official/favicon.ico", "image/x-icon"],
  ["/favicon-32.png", "official/favicon-32.png", "image/png"],
  ["/favicon-192.png", "official/favicon-192.png", "image/png"],
  ["/apple-touch-icon.png", "official/apple-touch-icon.png", "image/png"],
  // Variable fonts: one file each covers the weights the site uses (Geist 400 to 700, Mono 400 and 500).
  ["/fonts/geist.woff2", "fonts/Geist-Variable.woff2", "font/woff2"],
  ["/fonts/geist-mono.woff2", "fonts/GeistMono-Variable.woff2", "font/woff2"],
] as const;

if (import.meta.main) {
  const entries = ASSET_FILES.map(
    ([path, file, type]) =>
      `  ${JSON.stringify(path)}: {\n    type: ${JSON.stringify(type)},\n    base64:\n      ${JSON.stringify(readFileSync(join(brand, file)).toString("base64"))},\n  },`,
  ).join("\n");
  const out = `/* Generated by brand-assets.gen.ts from brand/ (favicons: the company's own, as blackark.uk serves
 them; fonts: Geist and Geist Mono by Vercel, SIL Open Font License 1.1, brand/fonts/LICENSE.txt).
 Do not edit; run the generator. */
export const BRAND_ASSETS: Record<string, { type: string; base64: string }> = {
${entries}
};
`;
  writeFileSync(join(import.meta.dir, "brand-assets.ts"), out);
  console.log(`wrote brand-assets.ts (${out.length} bytes)`);
}
