import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, resolve } from "node:path";
import { termsVersionOf } from "../shared/terms";
import {
  createApplicationConfiguration,
  loadTenantPackage,
} from "../server/src/tenant-package";

const projectRoot = resolve(import.meta.dir, "..");
const configuredTenantPackageDirectory = process.env.TENANT_PACKAGE_DIR;
const tenantPackageDirectory = configuredTenantPackageDirectory
  ? isAbsolute(configuredTenantPackageDirectory)
    ? configuredTenantPackageDirectory
    : resolve(projectRoot, "server", configuredTenantPackageDirectory)
  : resolve(projectRoot, "examples/fintech");
const tenantPackage = await loadTenantPackage(tenantPackageDirectory);
const applicationConfiguration = createApplicationConfiguration(tenantPackage);
const outputPath = resolve(
  projectRoot,
  "app/src/lib/generated/application-config.ts",
);

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  [
    "// This file is generated by scripts/generate-app-config.ts. Do not edit it.",
    "export type AppConfig = { brand: { tenantId: string; productName: string } };",
    `export const appConfig: AppConfig = ${JSON.stringify(applicationConfiguration, null, 2)};`,
    "",
  ].join("\n"),
);

// The privacy notice, so the app can show it at /privacy from the one source the lawyer edits
// (docs/legal/privacy-notice.md) instead of a second copy that drifts. Google's sign-in consent screen
// asks for this address, and a customer expects it before they sign up.
const privacyNotice = await readFile(
  resolve(projectRoot, "docs/legal/privacy-notice.md"),
  "utf8",
);
await writeFile(
  resolve(projectRoot, "app/src/lib/generated/privacy-notice.ts"),
  [
    "// This file is generated by scripts/generate-app-config.ts from docs/legal/privacy-notice.md. Do not edit it.",
    `export const privacyNotice: string = ${JSON.stringify(privacyNotice)};`,
    "",
  ].join("\n"),
);

// The terms of service, from the one file a lawyer edits (docs/legal/terms-of-service.md): the text
// for the app's /terms page, and the version for the server, which records which one each person
// accepted. The version file is committed (shared/terms-version.ts) and a test fails if it is stale.
const termsOfService = await readFile(
  resolve(projectRoot, "docs/legal/terms-of-service.md"),
  "utf8",
);
const termsVersion = termsVersionOf(termsOfService);
await writeFile(
  resolve(projectRoot, "app/src/lib/generated/terms.ts"),
  [
    "// This file is generated by scripts/generate-app-config.ts from docs/legal/terms-of-service.md. Do not edit it.",
    `export const termsOfService: string = ${JSON.stringify(termsOfService)};`,
    `export const termsVersion: string = ${JSON.stringify(termsVersion)};`,
    "",
  ].join("\n"),
);
await writeFile(
  resolve(projectRoot, "shared/terms-version.ts"),
  [
    "// Generated by scripts/generate-app-config.ts from docs/legal/terms-of-service.md. Do not edit it:",
    "// change the version line in that document and run the script.",
    `export const TERMS_VERSION = ${JSON.stringify(termsVersion)};`,
    "",
  ].join("\n"),
);
